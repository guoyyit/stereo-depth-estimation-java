package com.github.guoyyit.stereodepthestimationjava.tests;

import com.github.guoyyit.stereodepthestimationjava.calibration.RectificationEngine;
import com.github.guoyyit.stereodepthestimationjava.error.RectificationException;
import com.github.guoyyit.stereodepthestimationjava.model.CalibrationParams;
import com.github.guoyyit.stereodepthestimationjava.model.RectificationMaps;
import com.github.guoyyit.stereodepthestimationjava.synthetic.IndependentStereoModel;
import org.junit.jupiter.api.Test;

import java.util.Random;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * Validates the rectification geometry produced by {@link RectificationEngine} against
 * the {@link IndependentStereoModel}, an independent reference implementation of the
 * projection and distortion equations. Raw observations are generated by the
 * independent model only, so errors in the engine's distortion or epipolar
 * rectification mapping cannot cancel out.
 */
class RectificationGeometryTest {

    private static final int WIDTH = 200;
    private static final int HEIGHT = 160;
    private static final long SEED = 20261006L;

    /** Documented verification bounds (pixels) for the supported parameter range. */
    private static final double MAX_EPIPOLAR_RESIDUAL_PX = 0.5;
    private static final double MAX_REPROJECTION_RESIDUAL_PX = 0.5;
    private static final double MAX_DISPARITY_RESIDUAL_PX = 0.5;

    /** Strong but in-range calibration: |k| up to 0.25, rotation norm ~0.22 rad. */
    private static CalibrationParams strongCalibration() {
        double fx = WIDTH * 1.1;
        double[] k = {fx, 0, WIDTH / 2.0, 0, fx, HEIGHT / 2.0, 0, 0, 1};
        double[] d = {-0.25, 0.10, 0.004, -0.005, -0.03};
        double[] r = {0.12, -0.16, 0.08};
        double[] t = {-fx * 0.12, 0.0, 0.0};
        return CalibrationParams.create("calib-strong", WIDTH, HEIGHT, k, d, r, t);
    }

    @Test
    void rectifiedGeometryMatchesIndependentReferenceUnderStrongDistortionAndRotation() {
        CalibrationParams calibration = strongCalibration();
        RectificationMaps maps = new RectificationEngine().buildMaps(calibration);
        IndependentStereoModel reference = new IndependentStereoModel(calibration);

        double[] engineK = maps.rectifiedK();
        double[] referenceK = reference.rectifiedK();
        for (int i = 0; i < 4; i++) {
            assertEquals(referenceK[i], engineK[i], 1e-6 * Math.abs(referenceK[i]) + 1e-6,
                    "rectified intrinsics must agree with the independent reference");
        }

        Random random = new Random(SEED);
        double maxEpipolar = 0.0;
        double maxReprojection = 0.0;
        double maxDisparity = 0.0;
        int samples = 0;
        for (int n = 0; n < 2000; n++) {
            double z = 200.0 + random.nextDouble() * 600.0;
            double[] point = {
                    (random.nextDouble() - 0.5) * 0.8 * z,
                    (random.nextDouble() - 0.5) * 0.6 * z,
                    z};
            double[] rawLeft = reference.projectLeft(point);
            double[] rawRight = reference.projectRight(point);
            if (rawLeft[0] < 1 || rawLeft[0] > WIDTH - 2 || rawLeft[1] < 1
                    || rawLeft[1] > HEIGHT - 2 || rawRight[0] < 1 || rawRight[0] > WIDTH - 2
                    || rawRight[1] < 1 || rawRight[1] > HEIGHT - 2) {
                continue;
            }
            samples++;
            double[] rectLeft = invertMap(maps.mapXLeft(), maps.mapYLeft(), WIDTH, HEIGHT,
                    rawLeft[0], rawLeft[1]);
            double[] rectRight = invertMap(maps.mapXRight(), maps.mapYRight(), WIDTH, HEIGHT,
                    rawRight[0], rawRight[1]);

            maxEpipolar = Math.max(maxEpipolar, Math.abs(rectLeft[1] - rectRight[1]));

            double[] expectedLeft = reference.projectRectifiedLeft(point);
            double[] expectedRight = reference.projectRectifiedRight(point);
            maxReprojection = Math.max(maxReprojection,
                    Math.hypot(rectLeft[0] - expectedLeft[0], rectLeft[1] - expectedLeft[1]));
            maxReprojection = Math.max(maxReprojection,
                    Math.hypot(rectRight[0] - expectedRight[0], rectRight[1] - expectedRight[1]));

            double disparity = rectLeft[0] - rectRight[0];
            maxDisparity = Math.max(maxDisparity,
                    Math.abs(disparity - reference.idealDisparity(point)));
        }
        assertTrue(samples > 500, "expected enough in-view 3D samples, got " + samples);
        assertTrue(maxEpipolar <= MAX_EPIPOLAR_RESIDUAL_PX,
                "epipolar residual " + maxEpipolar + " px exceeds bound");
        assertTrue(maxReprojection <= MAX_REPROJECTION_RESIDUAL_PX,
                "reprojection residual " + maxReprojection + " px exceeds bound");
        assertTrue(maxDisparity <= MAX_DISPARITY_RESIDUAL_PX,
                "disparity residual " + maxDisparity + " px exceeds bound");
    }

    @Test
    void residualsAreReproducibleWithFixedSeed() {
        CalibrationParams calibration = strongCalibration();
        RectificationMaps maps = new RectificationEngine().buildMaps(calibration);
        IndependentStereoModel reference = new IndependentStereoModel(calibration);
        double first = maxEpipolarResidual(maps, reference, SEED);
        double second = maxEpipolarResidual(maps, reference, SEED);
        assertEquals(first, second, 0.0, "residuals must be exactly reproducible");
    }

    private static double maxEpipolarResidual(RectificationMaps maps,
                                              IndependentStereoModel reference, long seed) {
        Random random = new Random(seed);
        double max = 0.0;
        for (int n = 0; n < 500; n++) {
            double z = 200.0 + random.nextDouble() * 600.0;
            double[] point = {
                    (random.nextDouble() - 0.5) * 0.8 * z,
                    (random.nextDouble() - 0.5) * 0.6 * z,
                    z};
            double[] rawLeft = reference.projectLeft(point);
            double[] rawRight = reference.projectRight(point);
            if (rawLeft[0] < 1 || rawLeft[0] > WIDTH - 2 || rawLeft[1] < 1
                    || rawLeft[1] > HEIGHT - 2 || rawRight[0] < 1 || rawRight[0] > WIDTH - 2
                    || rawRight[1] < 1 || rawRight[1] > HEIGHT - 2) {
                continue;
            }
            double[] rectLeft = invertMap(maps.mapXLeft(), maps.mapYLeft(), WIDTH, HEIGHT,
                    rawLeft[0], rawLeft[1]);
            double[] rectRight = invertMap(maps.mapXRight(), maps.mapYRight(), WIDTH, HEIGHT,
                    rawRight[0], rawRight[1]);
            max = Math.max(max, Math.abs(rectLeft[1] - rectRight[1]));
        }
        return max;
    }

    @Test
    void extremeDistortionFailsExplicitly() {
        double fx = WIDTH * 1.1;
        double[] k = {fx, 0, WIDTH / 2.0, 0, fx, HEIGHT / 2.0, 0, 0, 1};
        double[] d = {-2.5, 0.10, 0.004, -0.005, -0.03};
        double[] r = {0.02, -0.01, 0.01};
        double[] t = {-fx * 0.12, 0.0, 0.0};
        CalibrationParams broken = CalibrationParams.create("calib-broken-distortion",
                WIDTH, HEIGHT, k, d, r, t);
        RectificationException error = assertThrows(RectificationException.class,
                () -> new RectificationEngine().buildMaps(broken));
        assertTrue(error.getMessage().contains("calib-broken-distortion"));
    }

    @Test
    void extremeRotationFailsExplicitly() {
        double fx = WIDTH * 1.1;
        double[] k = {fx, 0, WIDTH / 2.0, 0, fx, HEIGHT / 2.0, 0, 0, 1};
        double[] d = {-0.03, 0.005, 0.0002, -0.0002, 0.0};
        double[] r = {0.0, 1.2, 0.0};
        double[] t = {-fx * 0.12, 0.0, 0.0};
        CalibrationParams broken = CalibrationParams.create("calib-broken-rotation",
                WIDTH, HEIGHT, k, d, r, t);
        assertThrows(RectificationException.class,
                () -> new RectificationEngine().buildMaps(broken));
    }

    /**
     * Inverts the engine's rectification map field by Newton iteration on the bilinear
     * interpolation of the map, locating the rectified pixel whose source sample equals
     * the given raw point. Operates purely on the published map output.
     */
    private static double[] invertMap(float[] mapX, float[] mapY, int width, int height,
                                      double rawX, double rawY) {
        // Robust initial guess: nearest map node, then Newton polish. Strong distortion
        // moves the rectified coordinate far from the raw coordinate, so a naive
        // identity initial guess can converge to a wrong basin.
        double best = Double.POSITIVE_INFINITY;
        double x = 0;
        double y = 0;
        for (int ny = 0; ny < height; ny++) {
            for (int nx = 0; nx < width; nx++) {
                int i = ny * width + nx;
                double dx = mapX[i] - rawX;
                double dy = mapY[i] - rawY;
                double dist = dx * dx + dy * dy;
                if (dist < best) {
                    best = dist;
                    x = nx;
                    y = ny;
                }
            }
        }
        for (int iteration = 0; iteration < 60; iteration++) {
            int ix = (int) Math.floor(x);
            int iy = (int) Math.floor(y);
            ix = Math.max(0, Math.min(width - 2, ix));
            iy = Math.max(0, Math.min(height - 2, iy));
            double fx = Math.max(0.0, Math.min(1.0, x - ix));
            double fy = Math.max(0.0, Math.min(1.0, y - iy));
            int i00 = iy * width + ix;
            double mx = bilinear(mapX[i00], mapX[i00 + 1], mapX[i00 + width],
                    mapX[i00 + width + 1], fx, fy);
            double my = bilinear(mapY[i00], mapY[i00 + 1], mapY[i00 + width],
                    mapY[i00 + width + 1], fx, fy);
            double dxdx = (1 - fy) * (mapX[i00 + 1] - mapX[i00])
                    + fy * (mapX[i00 + width + 1] - mapX[i00 + width]);
            double dxdy = (1 - fx) * (mapX[i00 + width] - mapX[i00])
                    + fx * (mapX[i00 + width + 1] - mapX[i00 + 1]);
            double dydx = (1 - fy) * (mapY[i00 + 1] - mapY[i00])
                    + fy * (mapY[i00 + width + 1] - mapY[i00 + width]);
            double dydy = (1 - fx) * (mapY[i00 + width] - mapY[i00])
                    + fx * (mapY[i00 + width + 1] - mapY[i00 + 1]);
            double det = dxdx * dydy - dxdy * dydx;
            if (Math.abs(det) < 1e-9) {
                break;
            }
            double ex = mx - rawX;
            double ey = my - rawY;
            if (Math.abs(ex) < 1e-7 && Math.abs(ey) < 1e-7) {
                break;
            }
            x -= (dydy * ex - dxdy * ey) / det;
            y -= (-dydx * ex + dxdx * ey) / det;
            x = Math.max(0, Math.min(width - 1.0, x));
            y = Math.max(0, Math.min(height - 1.0, y));
        }
        return new double[] {x, y};
    }

    private static double bilinear(double v00, double v01, double v10, double v11,
                                   double fx, double fy) {
        double top = v00 + (v01 - v00) * fx;
        double bottom = v10 + (v11 - v10) * fx;
        return top + (bottom - top) * fy;
    }
}
